#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn handler_names_cover_dispatch_ids_and_unknown() {
        for (id, expected) in [
            (0x00, "spawn_object"),
            (0x20, "keepalive"),
            (0x28, "entity_relative_move"),
            (0x29, "entity_relative_move"),
            (0x44, "entity_metadata"),
            (0x5b, "tags"),
            (0x5c, "unknown"),
            (-1, "unknown"),
        ] {
            assert_eq!(handler_name(id), expected, "packet {id:#x}");
        }
        for id in 0x00..=0x5b {
            assert_ne!(handler_name(id), "unknown", "packet {id:#x}");
        }
    }
}
