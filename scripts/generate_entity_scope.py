#!/usr/bin/env python3
"""Generate the private all-registry exclusion table from original-JAR results.

No registry-name qualification list: iterate the exported official registry,
resolve native method owners and constant false/null contact predicates, and
retain every original ancestor method fingerprint. Semantic review is in
../docs/contact-scope-all-types.md. This does not qualify numerical contacts.
"""
import argparse
import gzip
import hashlib
import json
import re
import subprocess
from pathlib import Path
from audit_contact_capabilities import CLIENT, ROOT, audit, digest
from movement_oracle.run import VERSIONS, SPECIAL_SOURCE_SHA256

ORACLE = ROOT/'data/client_api/entity_scope_oracle.json.gz'
EVIDENCE = ROOT/'docs/evidence/contact-scope-all-types-20261025.json'
RUST = ROOT/'src/client/entity/scope_registry_generated.rs'


def classes(jar, roots):
    result = {}
    todo = set(roots)
    while todo:
        batch = sorted(todo-result.keys())
        if not batch:
            break
        todo = set()
        raw = subprocess.check_output(['javap','-c','-p','-classpath',str(jar),*batch],text=True)
        for block in raw.split('Compiled from ')[1:]:
            header = re.search(r'(?:class|interface) ([\w.$]+)(?:<[^\n]*?>)?(?: extends ([\w.$]+))?',block)
            if not header:
                continue
            cls,parent = header.groups()
            methods = {b.split('\n')[0].strip():b for b in re.split(r'\n(?=  [^ ])',block) if '    Code:' in b}
            result[cls] = dict(parent=parent,methods=methods)
            if parent and not parent.startswith('java.'):
                todo.add(parent)
    return result


def constant(cache, cls, method, instructions):
    row = cache[cls]
    bodies = [b for sig,b in row['methods'].items() if re.search(r' '+method+r'\(',sig)]
    if bodies:
        return all([line.strip().split(':',1)[1].strip() for line in b.splitlines()
                    if re.match(r'\s+\d+:',line)] == instructions for b in bodies)
    return bool(row['parent']) and constant(cache,row['parent'],method,instructions)


def render(versions):
    lines = ['// @generated by scripts/generate_entity_scope.py from hash-verified official JARs.',
             '// Exclusion-only: these rows never grant numerical contact qualification.',
             'use super::RegistryScope;', '']
    for version, rows in versions.items():
        lines.append('pub(super) static V'+version.replace('.','_')+': &[RegistryScope] = &[')
        for name,row in sorted(rows.items()):
            dims = lambda key: '['+', '.join(repr(float(x)) for x in row[key])+']'
            cases = '&['+', '.join('('+str(c['value'])+', ['+', '.join(repr(float(x)) for x in c['dimensions'])+'])' for c in row['size_cases'])+']'
            lines.append('    RegistryScope { name: '+json.dumps(name)+', dimensions: '+dims('dimensions')+', maximum: '+dims('maximum')+', size_index: '+('Some('+str(row['size_index'])+')' if row['size_index'] is not None else 'None')+', sizes: '+cases+', irrelevant: '+str(row['irrelevant']).lower()+', remote_hull: '+str(row['remote_hull']).lower()+', dependent: '+str(row['dependent_effect']).lower()+', placement_indices: &'+json.dumps(row['placement_indices'])+' },')
        lines += ['];','']
    return '\n'.join(lines)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--downloads',type=Path)
    p.add_argument('--work',type=Path)
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    oracle=json.loads(gzip.decompress(ORACLE.read_bytes()))
    if a.check:
        e=json.loads(EVIDENCE.read_text())
        assert e['oracle_sha256']==digest(ORACLE)
        for path,sha in e['source_sha256'].items():
            assert digest(ROOT/path)==sha,path
        for v,rows in e['versions'].items():
            assert set(rows['types'])=={r['name'] for r in oracle['versions'][v]['results']}
            assert (rows['client_jar_sha1'],rows['client_mappings_sha1'])==CLIENT[v]
            original={r['name']:r for r in oracle['versions'][v]['results']}
            for name,row in rows['types'].items():
                assert row['original']==original[name],(v,name,'oracle input')
                metadata=json.loads((ROOT/f'data/client_api/entity_data-{v}.json').read_text())['entities'][name]
                assert row['placement_indices']==[x[2] for x in metadata if x[0]=='Shulker' and x[1]=='DATA_ATTACH_POS_ID']
                assert row['size_cases']==original[name]['size_cases'],(v,name,'size cases')
                assert all(a>=b for a,b in zip(row['dimensions'],original[name]['default_dimensions'])),(v,name,'default shape')
                assert all(a>=b for a,b in zip(row['maximum'],original[name]['max_dimensions'])),(v,name,'maximum shape')
                assert row['irrelevant']==(row['false_push_proof'] and row['false_solid_proof'] and not row['dependent_effect'])
        generated=render({v:r['types'] for v,r in e['versions'].items()})
        # rustfmt is the canonical formatter for generated Rust as well.
        formatted=subprocess.check_output(['rustfmt','--edition','2024','--emit','stdout'],input=generated,text=True)
        assert RUST.read_text()==formatted
        print('PASS: every official registry type classified, generated Rust and source bindings match')
        return
    if a.downloads is None or a.work is None:
        p.error('--downloads and --work required')
    evidence=dict(schema=1,contract='A: received model origin and explicit numeric ticks; no server wall-time claim',
                  oracle_sha256=digest(ORACLE),versions={})
    for v,original in oracle['versions'].items():
        assert original['original_server_jar_sha1']==VERSIONS[v][0]
        for suffix,sha in zip(['client.jar','client-mappings.txt'],CLIENT[v]):
            assert digest(a.downloads/f'{v}-{suffix}','sha1')==sha
        named=a.work/v/'client-named.jar';named.parent.mkdir(parents=True,exist_ok=True)
        tool=a.downloads/'SpecialSource-1.11.4-shaded.jar'
        assert digest(tool)==SPECIAL_SOURCE_SHA256
        subprocess.run(['java','-jar',str(tool),'--in-jar',str(a.downloads/f'{v}-client.jar'),'--out-jar',str(named),
                        '--srg-in',str(a.downloads/f'{v}-client-mappings.txt')],check=True,stdout=subprocess.DEVNULL)
        owners=audit(named)
        roots={'net.minecraft.world.entity.EntityType','net.minecraft.world.entity.EntityDimensions',
               'net.minecraft.world.level.EntityGetter','net.minecraft.world.entity.EntitySelector',
               'net.minecraft.client.multiplayer.ClientPacketListener'}
        if v!='1.16.1':
            roots.update({'net.minecraft.world.entity.InterpolationHandler','net.minecraft.world.entity.EntityAttachments',
                          'net.minecraft.world.entity.vehicle.minecart.NewMinecartBehavior',
                          'net.minecraft.world.entity.vehicle.minecart.NewMinecartBehavior$MinecartStep',
                          'net.minecraft.network.protocol.game.ClientboundMoveMinecartPacket','net.minecraft.world.phys.Vec3$1'})
        cache=classes(named,{r['class_name'] for r in owners.values()}|roots)
        metadata=json.loads((ROOT/f'data/client_api/entity_data-{v}.json').read_text())['entities']
        rows={}
        for r in original['results']:
            name=r['name'];o=owners[name.removeprefix('minecraft:')];cls=o['class_name']
            false_push=constant(cache,cls,'isPushable',['iconst_0','ireturn'])
            false_solid=constant(cache,cls,'getCollideBox' if v=='1.16.1' else 'canBeCollidedWith',
                                 ['aconst_null','areturn'] if v=='1.16.1' else ['iconst_0','ireturn'])
            # These two native paths may affect an attached local player. Their
            # received target is tracked privately; an unattached instance is irrelevant.
            dependent=any('DATA_HOOKED_ENTITY'==x[1] or 'DATA_ATTACHED_TO_TARGET'==x[1] for x in metadata[name])
            assert not dependent or (false_push and false_solid),name
            irrelevant=false_push and false_solid and not dependent
            dims=r['default_dimensions'][:]
            unit=r['unit_max_dimensions'][:]
            maximum=r['max_dimensions'][:]
            # Integer-size variants use the received case; the other pose/age/
            # enum variants share their generated unit-scale maximum.
            if not r['size_cases']:
                dims=unit
            # Native Shulker opening extends up to one block in its attachment direction.
            if cls.endswith('.Shulker'):
                dims=[max(2.,x) for x in dims];unit=[max(2.,x) for x in unit]
                maximum=[max(x,2.*(1. if v=='1.16.1' else 16.)) for x in maximum]
            index=next((x[2] for x in metadata[name] if x[1]==r.get('size_field')),None)
            remote_hull=r['living'] or ('Minecart' in cls or 'Boat' in cls or 'Raft' in cls)
            rows[name]=dict(dimensions=dims,maximum=maximum,size_index=index,size_cases=r['size_cases'],
                            irrelevant=irrelevant,remote_hull=remote_hull,dependent_effect=dependent,
                            placement_indices=[x[2] for x in metadata[name] if x[0]=='Shulker' and x[1]=='DATA_ATTACH_POS_ID'],
                            original=r,owners=o,false_push_proof=false_push,false_solid_proof=false_solid)
        evidence['versions'][v]=dict(client_jar_sha1=CLIENT[v][0],client_mappings_sha1=CLIENT[v][1],
            client_named_sha256=digest(named),types=rows,method_sha256={cls:{sig:hashlib.sha256(b.encode()).hexdigest() for sig,b in c['methods'].items()} for cls,c in sorted(cache.items())})
        print(v,len(rows),'registry rows;',sum(r['irrelevant'] for r in rows.values()),'positive noncontacts',flush=True)
    RUST.write_text(render({v:r['types'] for v,r in evidence['versions'].items()}))
    subprocess.run(['rustfmt','--edition','2024',str(RUST)],check=True)
    sources=['scripts/generate_entity_scope.py','scripts/run_entity_scope_oracle.py',
             'scripts/entity_scope_oracle/1.16.1/EntityScopeOracle.java','scripts/entity_scope_oracle/1.21.11/EntityScopeOracle.java',
             'src/client/entity.rs','src/client/entity/scope.rs','src/client/entity/scope_registry_generated.rs',
             'src/versions/java_1_16_1/client/play_entities.rs','src/versions/java_1_21_11/client/entity.rs',
             'docs/contact-scope-all-types.md','docs/player-contact-scope.md','Cargo.toml']
    evidence['source_sha256']={path:digest(ROOT/path) for path in sources if (ROOT/path).exists()}
    EVIDENCE.write_text(json.dumps(evidence,indent=2)+'\n')

if __name__=='__main__':main()
